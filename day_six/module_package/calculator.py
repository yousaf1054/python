def add(a, b):
    return a + b


def subtract(a, b):
    return a - b


def multiply(a, b):
    return a * b


def divide(a, b):
    return a / b

if __name__ == "__main__":
    print(add(10, 5))       # 15
    print(subtract(10, 5))  # 5
    print(multiply(10, 5))  # 50
    print(divide(10, 5))    # 2.0